const int MV_SPRITE_COUNT =
    (int)(sizeof(MV_SPRITES) / sizeof(MV_SPRITES[0]));

const MvSprite *mv_sprite(const char *name)
{
    int i;

    if (name == NULL) {
        return NULL;
    }
    for (i = 0; i < MV_SPRITE_COUNT; ++i) {
        if (strcmp(MV_SPRITES[i].name, name) == 0) {
            return &MV_SPRITES[i];
        }
    }
    return NULL;
}
